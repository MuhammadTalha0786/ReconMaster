def build_report_data(
    scan_result: ScanResult,
    banners: Optional[List[Dict]] = None,
    nse_results: str = "",
    os_guess: str = "",
) -> ReportData:
    """Assemble a ReportData object from a raw ScanResult plus extras."""
    return ReportData(
        target=scan_result.target,
        date=human_timestamp(),
        duration=f"{scan_result.duration_seconds:.2f}s",
        command=" ".join(scan_result.command),
        open_ports=scan_result.open_ports,
        os_guess=os_guess,
        nse_results=nse_results,
        banners=banners or [],
        recommendations=DEFAULT_RECOMMENDATIONS,
        raw_output=scan_result.raw_output,
    )


