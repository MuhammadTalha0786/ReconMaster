from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

from config import APP_NAME, APP_VERSION, REPORTS_DIR
from scanner import ScanResult
from utils import (
    default_report_filename, ensure_directory, human_timestamp, sanitize_filename,
)


@dataclass
class ReportData:
    """Normalized data model shared by every report format."""
    target: str
    date: str
    duration: str
    command: str
    open_ports: List[Dict] = field(default_factory=list)
    closed_ports_summary: str = ""
    filtered_ports_summary: str = ""
    services: List[Dict] = field(default_factory=list)
    os_guess: str = ""
    nse_results: str = ""
    banners: List[Dict] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    raw_output: str = ""


@dataclass
class ReportSection:
    """One task's contribution to an aggregated multi-task report."""
    index: int
    label: str
    status: str
    command: str
    duration: str
    output: str
    error: str = ""
    banners: List[Dict] = field(default_factory=list)


@dataclass
class AggregatedReportData:
    """Report model for a multi-task ScanJob (see job.py)."""
    target: str
    scan_started: str
    scan_finished: str
    duration: str
    sections: List[ReportSection] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    summary: Dict[str, int] = field(default_factory=dict)


def build_job_report_data(job, notes: Optional[List[str]] = None) -> "AggregatedReportData":
    """
    Build an AggregatedReportData from a completed job.ScanJob. Kept
    free of a hard import of job.py's types to avoid a circular import
    (job.py does not import report.py); `job` is duck-typed here.
    """
    sections = [
        ReportSection(
            index=i + 1,
            label=task.label,
            status=task.status.value if hasattr(task.status, "value") else str(task.status),
            command=task.command or " ".join(task.args),
            duration=f"{task.duration_seconds:.2f}s" if task.duration_seconds else "-",
            output=task.stdout,
            error=task.stderr,
            banners=list(getattr(task, "banners", []) or []),
        )
        for i, task in enumerate(job.tasks)
    ]
    return AggregatedReportData(
        target=job.target,
        scan_started=job.started_at,
        scan_finished=job.ended_at,
        duration=f"{job.duration_seconds:.2f}s",
        sections=sections,
        notes=notes or [],
        summary=job.summary_counts(),
    )


def generate_aggregated_txt(data: AggregatedReportData, filepath: Path) -> Path:
    lines = [
        f"{APP_NAME} Report", "=" * 50,
        f"Target          : {data.target}",
        f"Scan Started    : {data.scan_started}",
        f"Scan Finished   : {data.scan_finished}",
        f"Duration        : {data.duration}", "",
    ]
    for s in data.sections:
        lines += [f"[{s.index}] {s.label} — {s.status}", "-" * 50,
                   f"Command  : {s.command}", f"Duration : {s.duration}"]
        if s.error:
            lines.append(f"Error    : {s.error}")
        lines += ["Output:", s.output or "(no output)"]
        if s.banners:
            lines += ["", "Banner Information:"]
            for b in s.banners:
                reach = "reachable" if b.get("reachable") else "unreachable"
                lines.append(f"  Port {b.get('port')} [{reach}]: {b.get('banner') or '(no banner)'}")
        lines.append("")

    if data.notes:
        lines += ["Notes", "-" * 50] + [f"  - {n}" for n in data.notes] + [""]

    lines += ["Summary", "-" * 50]
    for status, count in data.summary.items():
        lines.append(f"  {status.title()}: {count}")
    lines += ["", "-" * 50, f"Generated by {APP_NAME} v{APP_VERSION}"]

    filepath.write_text("\n".join(lines), encoding="utf-8")
    return filepath


def generate_aggregated_json(data: AggregatedReportData, filepath: Path) -> Path:
    payload = asdict(data)
    payload["generator"] = f"{APP_NAME} v{APP_VERSION}"
    filepath.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return filepath


def generate_aggregated_xml(data: AggregatedReportData, filepath: Path) -> Path:
    root = ET.Element("ReconMasterJobReport", version=APP_VERSION)
    meta = ET.SubElement(root, "Meta")
    ET.SubElement(meta, "Target").text = data.target
    ET.SubElement(meta, "ScanStarted").text = data.scan_started
    ET.SubElement(meta, "ScanFinished").text = data.scan_finished
    ET.SubElement(meta, "Duration").text = data.duration

    sections_el = ET.SubElement(root, "Sections")
    for s in data.sections:
        sec_el = ET.SubElement(sections_el, "Section", index=str(s.index), status=s.status)
        ET.SubElement(sec_el, "Label").text = s.label
        ET.SubElement(sec_el, "Command").text = s.command
        ET.SubElement(sec_el, "Duration").text = s.duration
        ET.SubElement(sec_el, "Error").text = s.error
        ET.SubElement(sec_el, "Output").text = s.output
        if s.banners:
            banner_info_el = ET.SubElement(sec_el, "BannerInformation")
            for b in s.banners:
                b_el = ET.SubElement(banner_info_el, "Banner",
                                      port=str(b.get("port", "")),
                                      reachable=str(bool(b.get("reachable"))))
                b_el.text = b.get("banner") or ""

    notes_el = ET.SubElement(root, "Notes")
    for n in data.notes:
        ET.SubElement(notes_el, "Note").text = n

    summary_el = ET.SubElement(root, "Summary")
    for status, count in data.summary.items():
        ET.SubElement(summary_el, "Status", name=status).text = str(count)

    tree = ET.ElementTree(root)
    ET.indent(tree, space="  ")
    tree.write(filepath, encoding="utf-8", xml_declaration=True)
    return filepath


