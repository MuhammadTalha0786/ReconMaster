"""
report.py
==========
Generates professional scan reports in TXT, XML, JSON, HTML, and PDF
formats from a ScanResult (see scanner.py). Each report includes
target, timing, the command executed, parsed port/service/OS data,
NSE results, banner information, and general recommendations.
"""

from __future__ import annotations

