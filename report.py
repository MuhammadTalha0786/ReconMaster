def generate_aggregated_pdf(data: AggregatedReportData, filepath: Path) -> Path:
    from xml.sax.saxutils import escape as xml_escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak

    esc = xml_escape
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("Title2", parent=styles["Title"], textColor=colors.HexColor("#1f6feb"))
    heading_style = ParagraphStyle("Heading2b", parent=styles["Heading2"], textColor=colors.HexColor("#0d419d"))
    body_style = styles["BodyText"]
    mono_style = ParagraphStyle("Mono2", parent=styles["Code"], fontSize=8, leading=10)

    doc = SimpleDocTemplate(str(filepath), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                             topMargin=2 * cm, bottomMargin=2 * cm)
    story = [Paragraph(f"{APP_NAME} — Job Report", title_style), Spacer(1, 0.4 * cm)]
    story.append(Paragraph(f"<b>Target:</b> {esc(data.target)}", body_style))
    story.append(Paragraph(f"<b>Started:</b> {esc(data.scan_started)}", body_style))
    story.append(Paragraph(f"<b>Finished:</b> {esc(data.scan_finished)}", body_style))
    story.append(Paragraph(f"<b>Duration:</b> {esc(data.duration)}", body_style))
    story.append(Spacer(1, 0.4 * cm))

    for s in data.sections:
        story.append(Paragraph(f"[{s.index}] {esc(s.label)} — {esc(s.status)}", heading_style))
        story.append(Paragraph(f"<b>Command:</b> {esc(s.command)} &nbsp; <b>Duration:</b> {esc(s.duration)}", body_style))
        if s.error:
            story.append(Paragraph(f"<b>Error:</b> {esc(s.error)}", body_style))
        for line in (s.output or "(no output)").splitlines()[:200]:
            story.append(Paragraph(esc(line).replace(" ", "&nbsp;"), mono_style))
        if s.banners:
            story.append(Paragraph("Banner Information", ParagraphStyle(
                "SubHeading", parent=body_style, fontName="Helvetica-Bold", spaceBefore=6)))
            for b in s.banners:
                reach = "reachable" if b.get("reachable") else "unreachable"
                banner_text = esc(b.get("banner") or "(no banner)")
                story.append(Paragraph(f"Port {esc(str(b.get('port')))} [{reach}]: {banner_text}", mono_style))
        story.append(Spacer(1, 0.3 * cm))

    story.append(PageBreak())
    story.append(Paragraph("Notes", heading_style))
    for n in data.notes or ["None"]:
        story.append(Paragraph(f"• {esc(n)}", body_style))
    story.append(Paragraph("Summary", heading_style))
    for status, count in data.summary.items():
        story.append(Paragraph(f"{esc(status.title())}: {count}", body_style))
    story.append(Spacer(1, 0.5 * cm))
    story.append(Paragraph(f"Generated by {APP_NAME} v{APP_VERSION}", styles["Italic"]))

    doc.build(story)
    return filepath


_AGGREGATED_GENERATORS = {
    "txt": generate_aggregated_txt,
    "json": generate_aggregated_json,
    "xml": generate_aggregated_xml,
    "html": generate_aggregated_html,
    "pdf": generate_aggregated_pdf,
}


def generate_job_report(
    data: AggregatedReportData, fmt: str, filename: Optional[str] = None, out_dir: Path = REPORTS_DIR
) -> Path:
    """Generate a single aggregated-job report in the given format."""
    fmt = fmt.lower()
    if fmt not in _AGGREGATED_GENERATORS:
        raise ValueError(f"Unsupported report format: {fmt}")
    ensure_directory(out_dir)
    if filename:
        filename = sanitize_filename(filename)
    if not filename:
        filename = default_report_filename(data.target, fmt)
    if not filename.endswith(f".{fmt}"):
        filename = f"{filename}.{fmt}"
    filepath = out_dir / filename
    return _AGGREGATED_GENERATORS[fmt](data, filepath)


def generate_job_reports(
    data: AggregatedReportData, formats: List[str], base_filename: Optional[str] = None,
    out_dir: Path = REPORTS_DIR,
) -> List[Path]:
    """Generate every format the user selected from the same job data —
    Nmap is never re-run merely to produce a different report format."""
    paths = []
    for fmt in formats:
        name = f"{base_filename}.{fmt}" if base_filename else None
        paths.append(generate_job_report(data, fmt, name, out_dir))
    return paths


