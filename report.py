"""
report.py
==========
Generates professional scan reports in TXT, XML, JSON, HTML, and PDF
formats from a ScanResult (see scanner.py). Each report includes
target, timing, the command executed, parsed port/service/OS data,
NSE results, banner information, and general recommendations.
"""

from __future__ import annotations

import html
import json
import xml.etree.ElementTree as ET
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

from config import APP_NAME, APP_VERSION, REPORTS_DIR
from scanner import ScanResult
from utils import (
    default_report_filename, ensure_directory, human_timestamp, sanitize_filename,
)


@dataclass
class ReportData:
    """Normalized data model shared by every report format."""
    target: str
    date: str
    duration: str
    command: str
    open_ports: List[Dict] = field(default_factory=list)
    closed_ports_summary: str = ""
    filtered_ports_summary: str = ""
    services: List[Dict] = field(default_factory=list)
    os_guess: str = ""
    nse_results: str = ""
    banners: List[Dict] = field(default_factory=list)
    recommendations: List[str] = field(default_factory=list)
    raw_output: str = ""


DEFAULT_RECOMMENDATIONS = [
    "Close or firewall any ports that are not required for business function.",
    "Keep exposed services patched and running supported versions.",
    "Disable verbose service banners where possible to reduce fingerprinting.",
    "Review NSE 'vuln' script findings promptly and validate manually before remediation.",
    "Restrict management ports (SSH, RDP, etc.) to trusted source addresses only.",
]


def build_report_data(
    scan_result: ScanResult,
    banners: Optional[List[Dict]] = None,
    nse_results: str = "",
    os_guess: str = "",
) -> ReportData:
    """Assemble a ReportData object from a raw ScanResult plus extras."""
    return ReportData(
        target=scan_result.target,
        date=human_timestamp(),
        duration=f"{scan_result.duration_seconds:.2f}s",
        command=" ".join(scan_result.command),
        open_ports=scan_result.open_ports,
        os_guess=os_guess,
        nse_results=nse_results,
        banners=banners or [],
        recommendations=DEFAULT_RECOMMENDATIONS,
        raw_output=scan_result.raw_output,
    )


# ---------------------------------------------------------------------------
# TXT
# ---------------------------------------------------------------------------

def generate_txt(data: ReportData, filepath: Path) -> Path:
    lines = [
        f"{APP_NAME} v{APP_VERSION} — Scan Report",
        "=" * 50,
        f"Target       : {data.target}",
        f"Date         : {data.date}",
        f"Duration     : {data.duration}",
        f"Command      : {data.command}",
        "",
        "Open Ports",
        "-" * 50,
    ]
    if data.open_ports:
        for p in data.open_ports:
            lines.append(f"  {p.get('port')}/{p.get('protocol', 'tcp')}  {p.get('service', '')}")
    else:
        lines.append("  (none parsed — see raw output below)")

    if data.os_guess:
        lines += ["", "Operating System", "-" * 50, f"  {data.os_guess}"]

    if data.nse_results:
        lines += ["", "NSE Script Results", "-" * 50, data.nse_results]

    if data.banners:
        lines += ["", "Banner Information", "-" * 50]
        for b in data.banners:
            lines.append(f"  {b.get('port')}: {b.get('banner') or '(no banner)'}")

    lines += ["", "Recommendations", "-" * 50]
    lines += [f"  - {r}" for r in data.recommendations]

    lines += ["", "Raw Nmap Output", "-" * 50, data.raw_output]
    lines += ["", "-" * 50, f"Generated by {APP_NAME} v{APP_VERSION}"]

    filepath.write_text("\n".join(lines), encoding="utf-8")
    return filepath


# ---------------------------------------------------------------------------
# JSON
# ---------------------------------------------------------------------------

def generate_json(data: ReportData, filepath: Path) -> Path:
    payload = asdict(data)
    payload["generator"] = f"{APP_NAME} v{APP_VERSION}"
    filepath.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return filepath


# ---------------------------------------------------------------------------
# XML
# ---------------------------------------------------------------------------

def generate_xml(data: ReportData, filepath: Path) -> Path:
    root = ET.Element("ReconMasterReport", version=APP_VERSION)

    meta = ET.SubElement(root, "Meta")
    ET.SubElement(meta, "Target").text = data.target
    ET.SubElement(meta, "Date").text = data.date
    ET.SubElement(meta, "Duration").text = data.duration
    ET.SubElement(meta, "Command").text = data.command

    ports_el = ET.SubElement(root, "OpenPorts")
    for p in data.open_ports:
        port_el = ET.SubElement(ports_el, "Port")
        port_el.set("number", str(p.get("port", "")))
        port_el.set("protocol", str(p.get("protocol", "tcp")))
        port_el.text = str(p.get("service", ""))

    ET.SubElement(root, "OperatingSystem").text = data.os_guess
    ET.SubElement(root, "NSEResults").text = data.nse_results

    banners_el = ET.SubElement(root, "Banners")
    for b in data.banners:
        b_el = ET.SubElement(banners_el, "Banner")
        b_el.set("port", str(b.get("port", "")))
        b_el.text = b.get("banner") or ""

    rec_el = ET.SubElement(root, "Recommendations")
    for r in data.recommendations:
        ET.SubElement(rec_el, "Item").text = r

    ET.SubElement(root, "RawOutput").text = data.raw_output

    tree = ET.ElementTree(root)
    ET.indent(tree, space="  ")
    tree.write(filepath, encoding="utf-8", xml_declaration=True)
    return filepath


