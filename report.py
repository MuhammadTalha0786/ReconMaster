    story.append(Paragraph("Raw Nmap Output", heading_style))
    for line in data.raw_output.splitlines() or ["(no output)"]:
        story.append(Paragraph(esc(line).replace(" ", "&nbsp;"), mono_style))

    story.append(Spacer(1, 1 * cm))
    story.append(Paragraph(f"Generated by {APP_NAME} v{APP_VERSION}", styles["Italic"]))

    doc.build(story)
    return filepath


