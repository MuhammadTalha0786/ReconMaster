def generate_xml(data: ReportData, filepath: Path) -> Path:
    root = ET.Element("ReconMasterReport", version=APP_VERSION)

    meta = ET.SubElement(root, "Meta")
    ET.SubElement(meta, "Target").text = data.target
    ET.SubElement(meta, "Date").text = data.date
    ET.SubElement(meta, "Duration").text = data.duration
    ET.SubElement(meta, "Command").text = data.command

    ports_el = ET.SubElement(root, "OpenPorts")
    for p in data.open_ports:
        port_el = ET.SubElement(ports_el, "Port")
        port_el.set("number", str(p.get("port", "")))
        port_el.set("protocol", str(p.get("protocol", "tcp")))
        port_el.text = str(p.get("service", ""))

    ET.SubElement(root, "OperatingSystem").text = data.os_guess
    ET.SubElement(root, "NSEResults").text = data.nse_results

    banners_el = ET.SubElement(root, "Banners")
    for b in data.banners:
        b_el = ET.SubElement(banners_el, "Banner")
        b_el.set("port", str(b.get("port", "")))
        b_el.text = b.get("banner") or ""

    rec_el = ET.SubElement(root, "Recommendations")
    for r in data.recommendations:
        ET.SubElement(rec_el, "Item").text = r

    ET.SubElement(root, "RawOutput").text = data.raw_output

    tree = ET.ElementTree(root)
    ET.indent(tree, space="  ")
    tree.write(filepath, encoding="utf-8", xml_declaration=True)
    return filepath


