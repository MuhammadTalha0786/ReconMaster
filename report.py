_GENERATORS = {
    "txt": generate_txt,
    "json": generate_json,
    "xml": generate_xml,
    "html": generate_html,
    "pdf": generate_pdf,
}


def generate_report(
    data: ReportData, fmt: str, filename: Optional[str] = None, out_dir: Path = REPORTS_DIR
) -> Path:
    """
    Generate a single report in the given format ('txt'|'json'|'xml'|'html'|'pdf').
    Returns the path to the written file.
    """
    fmt = fmt.lower()
    if fmt not in _GENERATORS:
        raise ValueError(f"Unsupported report format: {fmt}")

    ensure_directory(out_dir)

    if filename:
        # Strip any directory components / traversal sequences the user
        # may have entered ('../', an absolute path, etc.) so the report
        # can never be written outside out_dir.
        filename = sanitize_filename(filename)

    if not filename:
        filename = default_report_filename(data.target, fmt)
    if not filename.endswith(f".{fmt}"):
        filename = f"{filename}.{fmt}"

    filepath = out_dir / filename
    return _GENERATORS[fmt](data, filepath)


def generate_all_formats(
    data: ReportData, base_filename: Optional[str] = None, out_dir: Path = REPORTS_DIR
) -> List[Path]:
    """Generate every supported report format for the same scan data."""
    paths = []
    for fmt in _GENERATORS:
        name = f"{base_filename}.{fmt}" if base_filename else None
        paths.append(generate_report(data, fmt, name, out_dir))
    return paths
