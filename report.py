def generate_txt(data: ReportData, filepath: Path) -> Path:
    lines = [
        f"{APP_NAME} v{APP_VERSION} — Scan Report",
        "=" * 50,
        f"Target       : {data.target}",
        f"Date         : {data.date}",
        f"Duration     : {data.duration}",
        f"Command      : {data.command}",
        "",
        "Open Ports",
        "-" * 50,
    ]
    if data.open_ports:
        for p in data.open_ports:
            lines.append(f"  {p.get('port')}/{p.get('protocol', 'tcp')}  {p.get('service', '')}")
    else:
        lines.append("  (none parsed — see raw output below)")

    if data.os_guess:
        lines += ["", "Operating System", "-" * 50, f"  {data.os_guess}"]

    if data.nse_results:
        lines += ["", "NSE Script Results", "-" * 50, data.nse_results]

    if data.banners:
        lines += ["", "Banner Information", "-" * 50]
        for b in data.banners:
            lines.append(f"  {b.get('port')}: {b.get('banner') or '(no banner)'}")

    lines += ["", "Recommendations", "-" * 50]
    lines += [f"  - {r}" for r in data.recommendations]

    lines += ["", "Raw Nmap Output", "-" * 50, data.raw_output]
    lines += ["", "-" * 50, f"Generated by {APP_NAME} v{APP_VERSION}"]

    filepath.write_text("\n".join(lines), encoding="utf-8")
    return filepath


